// Command artifact-keys exports the object-store content addresses the queue
// ledger still references.
//
// Object-store garbage collection is reference-driven: the store cannot know
// which of its immutable objects a job row still owns. This command answers
// that question from the only authority — the PostgreSQL ledger — and writes a
// file the objectstore's `-gc -referenced` pass reads. It is read-only: it
// never marks or deletes a row.
package main

import (
	"context"
	"database/sql"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"sort"
	"strings"
	"text/tabwriter"
	"time"

	"github.com/Marcuss-ops/RenderingGen/queue/internal/migrate"
	_ "github.com/jackc/pgx/v5/stdlib"
)

// ExportStats records what the export saw. SkippedNonCanonical counts ledger
// values that cannot name an object-store address (an older artifact naming
// scheme, a Drive URL); they are reported on stderr instead of being written,
// because a non-canonical line would make the GC reference file invalid.
type ExportStats struct {
	Referenced          int
	SkippedNonCanonical int
}

func main() {
	dbURL := flag.String("db-url", "", "PostgreSQL DSN (defaults to $DATABASE_URL)")
	out := flag.String("out", "-", "output file, or - for stdout")
	applyMigrations := flag.Bool("migrate", false, "apply pending migrations before exporting")
	timeout := flag.Duration("timeout", 2*time.Minute, "export timeout")
	flag.Parse()

	dsn := strings.TrimSpace(*dbURL)
	if dsn == "" {
		dsn = strings.TrimSpace(os.Getenv("DATABASE_URL"))
	}
	if dsn == "" {
		log.Fatal("artifact-keys: -db-url or $DATABASE_URL is required")
	}

	ctx, cancel := context.WithTimeout(context.Background(), *timeout)
	defer cancel()

	db, err := sql.Open("pgx", dsn)
	if err != nil {
		log.Fatalf("artifact-keys: open database: %v", err)
	}
	defer db.Close()
	if err := db.PingContext(ctx); err != nil {
		log.Fatalf("artifact-keys: connect database: %v", err)
	}
	if *applyMigrations {
		if err := migrate.Apply(ctx, db); err != nil {
			log.Fatalf("artifact-keys: apply migrations: %v", err)
		}
	}

	var writer io.Writer = os.Stdout
	if *out != "-" {
		file, err := os.Create(*out)
		if err != nil {
			log.Fatalf("artifact-keys: create %s: %v", *out, err)
		}
		defer file.Close()
		writer = file
	}

	stats, err := exportReferencedKeys(ctx, db, writer)
	if err != nil {
		log.Fatalf("artifact-keys: export: %v", err)
	}
	log.Printf("artifact-keys: referenced=%d skipped_non_canonical=%d", stats.Referenced, stats.SkippedNonCanonical)
}

// exportReferencedKeys writes one canonical content address per line. Both the
// artifact address and the raw-timing-sidecar address are part of the ledger:
// a GC that only protected the clip would delete the sidecar it points at.
func exportReferencedKeys(ctx context.Context, db *sql.DB, out io.Writer) (ExportStats, error) {
	rows, err := db.QueryContext(ctx, `
		SELECT storage_key FROM render_artifacts
		 WHERE storage_key IS NOT NULL AND btrim(storage_key) <> ''
		UNION
		SELECT chronon_timing_storage_key FROM render_artifacts
		 WHERE chronon_timing_storage_key IS NOT NULL AND btrim(chronon_timing_storage_key) <> ''
		ORDER BY 1`)
	if err != nil {
		return ExportStats{}, err
	}
	defer rows.Close()

	var keys []string
	stats := ExportStats{}
	for rows.Next() {
		var key string
		if err := rows.Scan(&key); err != nil {
			return ExportStats{}, err
		}
		key = strings.TrimSpace(key)
		if !isContentAddress(key) {
			stats.SkippedNonCanonical++
			log.Printf("artifact-keys: WARN skipping non-canonical ledger key %q", key)
			continue
		}
		keys = append(keys, key)
	}
	if err := rows.Err(); err != nil {
		return ExportStats{}, err
	}
	sort.Strings(keys)

	writer := tabwriter.NewWriter(out, 0, 8, 1, ' ', 0)
	fmt.Fprintf(writer, "# render_artifacts.storage_key + chronon_timing_storage_key\n")
	fmt.Fprintf(writer, "# generated by queue/cmd/artifact-keys; one sha256 content address per line\n")
	for _, key := range keys {
		fmt.Fprintln(writer, key)
	}
	if err := writer.Flush(); err != nil {
		return ExportStats{}, err
	}
	stats.Referenced = len(keys)
	return stats, nil
}

func isContentAddress(value string) bool {
	if len(value) != 64 {
		return false
	}
	for i := 0; i < len(value); i++ {
		c := value[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'f') {
			return false
		}
	}
	return true
}
