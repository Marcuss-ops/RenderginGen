// goldenRootFromSource is the fixture tree relative to this file. Resolving it
// from runtime.Caller instead of the process working directory is deliberate:
// the manifest gate must not depend on where `go test` was started, the same
// property the catalog loader lost and RGA-01 restored.
const goldenRootFromSource = "../../../testdata/golden"

// manifestSkippedDirs are locally generated assets that are intentionally not
// versioned (they are regenerated by the certification harness and are ~44 MB).
// Every other file in the fixture tree must appear in SHA256SUMS.
var manifestSkippedDirs = []string{"assets/semantic"}

// requiredGoldenFixtures pins the assets whose absence used to make CI green by
// skipping. A manifest that dropped one of these would still be self-consistent,
// so the list is asserted explicitly.
var requiredGoldenFixtures = []string{
	"background.mp4",
	"background.jpg",
	"Pale-Olive.mp4",
	"apple.png",
	"assets/apple.png",
	"assets/fonts/Poppins-Bold.ttf",
	"assets/fonts/Inter.ttf",
	"assets/fonts/PlayfairDisplay.ttf",
	"assets/fonts/Bricolage-Grotesque.ttf",
	"assets/fonts/DejaVuSans.ttf",
	"Poppins-Bold.ttf",
	"fonts/Poppins-Bold.ttf",
	"overlay_globe.png",
	"golden-semantic-overlay-job-v1.json",
}

// TestGoldenFixturesMatchChecksumManifest makes the fixture tree verifiable:
// every versioned asset has a recorded SHA-256, a changed byte fails the test,
// and a new file cannot appear without being added to the manifest. This is
// what turns "the fixtures happen to be in the developer's checkout" into a
// reproducible CI contract.
func TestGoldenFixturesMatchChecksumManifest(t *testing.T) {
	root := goldenRoot(t)
	entries, order := readGoldenManifest(t, filepath.Join(root, "SHA256SUMS"))

	if len(entries) == 0 {
		t.Fatal("SHA256SUMS lists no fixtures")
	}
	for _, name := range requiredGoldenFixtures {
		if _, ok := entries[name]; !ok {
			t.Errorf("required fixture %q is missing from SHA256SUMS", name)
		}
	}

	for _, name := range order {
		path := filepath.Join(root, filepath.FromSlash(name))
		got, err := hashFile(path)
		if err != nil {
			t.Errorf("%s: %v (the manifest names a fixture that is not in the checkout)", name, err)
			continue
		}
		if got != entries[name] {
			t.Errorf("%s: sha256 = %s, manifest says %s (update SHA256SUMS only for an intentional fixture change)", name, got, entries[name])
		}
	}

	// Coverage: a file added to the fixture tree without a manifest entry is
	// invisible to the hash check above, which is exactly how the original
	// background.mp4/font drift stayed unnoticed.
	listed := make(map[string]bool, len(order))
	for _, name := range order {
		listed[name] = true
	}
	var unlisted []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			for _, skip := range manifestSkippedDirs {
				if rel == skip {
					return filepath.SkipDir
				}
			}
			return nil
		}
		switch rel {
		case "SHA256SUMS", "PROVENANCE.md":
			return nil
		}
		if !listed[rel] {
			unlisted = append(unlisted, rel)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk fixture tree: %v", err)
	}
	sort.Strings(unlisted)
	for _, name := range unlisted {
		t.Errorf("fixture %q is not in SHA256SUMS (add it, or document why it is local-only)", name)
	}
}

// TestGoldenManifestRejectsPathsOutsideTheFixtureTree pins the manifest parser:
// a compromised or fat-fingered manifest must not be able to hash an arbitrary
// host file and report it as a fixture.
func TestGoldenManifestRejectsPathsOutsideTheFixtureTree(t *testing.T) {
	dir := t.TempDir()
	manifest := filepath.Join(dir, "SHA256SUMS")
	body := strings.Repeat("0", 64) + "  ../../etc/passwd\n"
	if err := os.WriteFile(manifest, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := parseGoldenManifest(manifest); err == nil {
		t.Fatal("manifest path escaping the fixture tree was accepted")
	}
}

func goldenRoot(t *testing.T) string {
	t.Helper()
	_, source, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller could not locate the fixture test")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(source), filepath.FromSlash(goldenRootFromSource)))
}

func readGoldenManifest(t *testing.T, path string) (map[string]string, []string) {
	t.Helper()
	entries, err := parseGoldenManifest(path)
	if err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	order := make([]string, 0, len(entries))
	for name := range entries {
		order = append(order, name)
	}
	sort.Strings(order)
	return entries, order
}

func parseGoldenManifest(path string) (map[string]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	entries := make(map[string]string)
	scanner := bufio.NewScanner(file)
	line := 0
	for scanner.Scan() {
		line++
		text := strings.TrimSpace(scanner.Text())
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		fields := strings.SplitN(text, "  ", 2)
		if len(fields) != 2 {
			return nil, fmt.Errorf("line %d: want '<sha256>  <path>', got %q", line, text)
		}
		sum, name := fields[0], fields[1]
		if len(sum) != sha256.Size*2 {
			return nil, fmt.Errorf("line %d: sha256 must be 64 hex characters, got %q", line, sum)
		}
		if _, err := hex.DecodeString(sum); err != nil {
			return nil, fmt.Errorf("line %d: invalid sha256 %q: %w", line, sum, err)
		}
		name = filepath.ToSlash(name)
		if !filepath.IsLocal(filepath.FromSlash(name)) || strings.HasPrefix(name, "../") {
			return nil, fmt.Errorf("line %d: path %q escapes the fixture tree", line, name)
		}
		if _, exists := entries[name]; exists {
			return nil, fmt.Errorf("line %d: duplicate entry for %q", line, name)
		}
		entries[name] = sum
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	return entries, nil
}

func hashFile(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()
	hasher := sha256.New()
	if _, err := io.Copy(hasher, file); err != nil {
		return "", err
	}
	return hex.EncodeToString(hasher.Sum(nil)), nil
}
